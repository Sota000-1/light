const { chromium } = require('playwright');
const { io: connect } = require('socket.io-client');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { server, io } = require('../server');
let browser, observer;
(async () => {
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  const origin = `http://127.0.0.1:${server.address().port}`;
  let latest = null, updates = 0;
  observer = connect(origin, { transports: ['websocket'] });
  await new Promise(r => observer.once('connect', r));
  observer.on('show-state', data => { latest = data.show; updates++; }); observer.emit('join-admin', { eventId: 'main' });
  browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}), args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  const page = await ctx.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin + '/admin.html');
  await page.waitForFunction(() => document.getElementById('connection').textContent.includes('接続済み'));
  const clients = [];
  for (const group of ['1組', '2組']) {
    const p = await ctx.newPage(); await p.goto(origin + '/client.html?event=main'); await p.getByRole('button', { name: group, exact: true }).click(); await p.locator('#screenBtn').click(); clients.push(p);
  }
  await page.locator('#realtimeTab').click();
  await page.locator('#rtColors [data-color="#0088ff"]').click();
  await Promise.all(clients.map(p => p.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(0, 136, 255)')));
  await page.locator('#rtOn').click(); await page.waitForFunction(() => document.querySelectorAll('#rtPhones .torch.on').length === 4);
  await page.keyboard.press('2'); await page.keyboard.press('q');
  await clients[1].waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(255, 0, 85)');
  assert.equal(await clients[0].evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(0, 136, 255)');
  await page.waitForFunction(() => document.querySelectorAll('#rtPhones .torch.on').length === 4);
  await page.keyboard.press('j'); await page.waitForFunction(() => !document.querySelectorAll('#rtPhones .torch')[1].classList.contains('on'));
  assert.equal(await page.locator('#rtPhones .torch.on').count(), 3);
  console.log('PASS: onscreen and keyboard controls operate without a song; class and screen/torch states remain independent');
  const beforeTyping = updates;
  await page.locator('#rtInterval').fill('1'); await page.keyboard.press('w'); await page.waitForTimeout(120);
  assert.equal(updates, beforeTyping);
  await page.locator('#realtime h1').click(); await page.keyboard.press('l');
  await page.waitForFunction(() => document.getElementById('rtStatus').textContent.includes('リアルタイム操作中'));
  await page.waitForTimeout(100);
  const ramp = latest.cues.find(c => c.group === '2組' && c.type === 'pulse');
  assert.equal(ramp.interval, 1000); assert.equal(ramp.intervalEnd, 200); assert.equal(ramp.rampDuration, 5);
  const beforeRepeat = updates;
  await page.keyboard.down('h'); await page.keyboard.down('h'); await page.keyboard.up('h'); await page.waitForTimeout(120);
  assert.equal(updates, beforeRepeat + 1);
  await page.keyboard.press('Space'); await page.waitForTimeout(400);
  assert.equal(await page.locator('#rtPhones .torch.on').count(), 3);
  assert.equal(await clients[1].evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(255, 0, 85)');
  console.log('PASS: acceleration settings reach the server; input fields and repeated keydown are ignored; momentary flash ends');
  await page.keyboard.press('Escape');
  await Promise.all(clients.map(p => p.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(0, 0, 0)')));
  await page.locator('#rtKeyboard').uncheck(); await page.locator('#realtime h1').click();
  const beforeDisabled = updates; await page.keyboard.press('q'); await page.waitForTimeout(100); assert.equal(updates, beforeDisabled);
  await page.locator('#rtKeyboard').check();
  await page.locator('#editTab').click(); await page.keyboard.press('w'); await page.waitForTimeout(100); assert.equal(updates, beforeDisabled);
  console.log('PASS: all-class keyboard stop, disabling shortcuts and leaving the realtime screen');
  await page.locator('#demoSong').click(); await page.waitForFunction(() => document.querySelectorAll('.clip').length === 5);
  await page.locator('.torch-clip').filter({ hasText: 'ビート' }).click();
  await page.locator('#cueRamp').check(); await page.locator('#cueInterval').fill('1'); await page.locator('#cueIntervalEnd').fill('0.2'); await page.locator('#cueForm button[type=submit]').click();
  await page.waitForFunction(() => document.getElementById('saveStatus').textContent === '保存済み');
  const dl = page.waitForEvent('download'); await page.locator('#exportProject').click();
  const backup = JSON.parse(await fs.readFile(await (await dl).path(), 'utf8'));
  const pulse = backup.songs[0].cues.find(c => c.type === 'pulse');
  assert.equal(pulse.interval, 1000); assert.equal(pulse.intervalEnd, 200); assert.equal(pulse.rampDuration, pulse.duration);
  await page.reload(); await page.waitForFunction(() => document.querySelectorAll('.clip').length === 5);
  await page.locator('.torch-clip').filter({ hasText: 'ビート' }).click(); assert.equal(await page.locator('#cueRamp').isChecked(), true);
  await page.locator('#cueDuration').fill('5'); await page.locator('#cueForm button[type=submit]').click();
  await page.locator('#realtimeTab').click();
  await fs.mkdir('test-results', { recursive: true }); await page.screenshot({ path: 'test-results/realtime-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: 'test-results/realtime-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: timeline acceleration editing, backup/reload and responsive realtime screen');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { observer?.disconnect(); if (browser) await browser.close(); await new Promise(r => io.close(r)); });
