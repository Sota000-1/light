const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { server, io } = require('../server');
let browser;
(async () => {
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  const origin = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}), args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1200 } });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin + '/admin.html');
  await page.waitForFunction(() => document.getElementById('connection').textContent.includes('接続済み'));
  await page.locator('#demoSong').click();
  await page.waitForFunction(() => document.querySelectorAll('.clip').length === 5);
  await page.locator('#classLanes').click();
  assert.equal(await page.locator('.effect-track').count(), 10);
  await page.locator('#classLanes').click();
  assert.equal(await page.locator('.effect-track').count(), 10);
  const groups = ['1組', '2組', '3組', '4組'];
  const colors = ['#ff0055', '#0088ff', '#00cc44', '#9900ff'];
  for (let i = 0; i < 4; i++) {
    await page.locator('#activeLane').selectOption({ label: `${groups[i]} · 画面` });
    await page.locator('[data-add=color]').click();
    await page.locator('#cueLabel').fill(`${groups[i]} color`);
    await page.locator('#cueDuration').fill('6'); await page.locator('#cueColor').fill(colors[i]);
    await page.locator('#cueForm button[type=submit]').click();
    assert.equal(await page.locator('#cueGroup').inputValue(), groups[i]);
    await page.locator('#activeLane').selectOption({ label: `${groups[i]} · ライト` });
    await page.locator(`[data-add=${i === 3 ? 'pulse' : 'torch'}]`).click();
    if (i !== 3) await page.locator('#cueTorch').selectOption(i === 1 ? 'false' : 'true');
    await page.locator('#cueDuration').fill('6'); await page.locator('#cueForm button[type=submit]').click();
  }
  const seek = async t => page.locator('#seek').evaluate((el, t) => { el.value = t; el.dispatchEvent(new Event('change')); }, t);
  await seek(1.25);
  const expected = ['rgb(255, 0, 85)', 'rgb(0, 136, 255)', 'rgb(0, 204, 68)', 'rgb(153, 0, 255)'];
  await page.waitForFunction(colors => Array.from(document.querySelectorAll('.phone')).every((el, i) => getComputedStyle(el).backgroundColor === colors[i]), expected);
  assert.equal(await page.locator('.torch.on').count(), 3);
  console.log('PASS: add class lanes without duplication; four independent simultaneous screen/torch previews');
  // A clip can cross compatible lanes and undo restores the original target.
  await page.locator('#activeLane').selectOption({ label: '1組 · 画面' });
  const sourceId = await page.locator('#activeLane').inputValue();
  await page.locator('#activeLane').selectOption({ label: '2組 · 画面' });
  const targetId = await page.locator('#activeLane').inputValue();
  await page.locator('#activeLane').selectOption(sourceId);
  const clip = page.locator(`.effect-track[data-lane-id="${sourceId}"] .clip`);
  await clip.scrollIntoViewIfNeeded();
  const source = await clip.boundingBox(), target = await page.locator(`.effect-track[data-lane-id="${targetId}"]`).boundingBox();
  await page.mouse.move(source.x + 25, source.y + 20); await page.mouse.down(); await page.mouse.move(source.x + 25, target.y + 25, { steps: 10 }); await page.mouse.up();
  assert.equal(await page.locator('#cueGroup').inputValue(), '2組');
  await page.locator('#undo').click(); assert.equal(await page.locator('#cueGroup').inputValue(), '1組');
  await page.locator('#editLane').click(); await page.locator('#laneName').fill('1組サビ'); await page.locator('#laneForm button[type=submit]').click();
  assert.ok(await page.locator('#activeLane option:checked').textContent().then(t => t.includes('1組サビ')));
  page.once('dialog', dialog => dialog.accept()); await page.locator('#deleteLane').click();
  assert.equal(await page.locator('.effect-track').count(), 9);
  await page.locator('#undo').click(); assert.equal(await page.locator('.effect-track').count(), 10);
  await page.locator('#addLane').click(); await page.locator('#laneName').fill('3組ソロ'); await page.locator('#laneGroup').selectOption('3組'); await page.locator('#laneForm button[type=submit]').click();
  assert.equal(await page.locator('.effect-track').count(), 11);
  console.log('PASS: lane-to-lane drag, lane rename/add/delete and undo');
  await page.waitForFunction(() => document.getElementById('saveStatus').textContent === '保存済み');
  await page.reload(); await page.waitForFunction(() => document.querySelectorAll('.effect-track').length === 11);
  assert.ok(await page.locator('#activeLane option').allTextContents().then(labels => labels.some(l => l.includes('1組サビ')) && labels.some(l => l.includes('3組ソロ'))));
  const downloaded = page.waitForEvent('download'); await page.locator('#exportProject').click();
  const backup = JSON.parse(await fs.readFile(await (await downloaded).path(), 'utf8'));
  assert.equal(backup.songs[0].lanes.length, 11);
  await page.locator('#importProject').setInputFiles({ name: 'lanes.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  await page.waitForFunction(() => document.querySelectorAll('.song-item').length === 2);
  assert.equal(await page.locator('.effect-track').count(), 11);
  await page.locator('.song-item').first().click();
  console.log('PASS: lane names, empty lanes, class assignments and cue membership survive save/reload and backup restore');
  const participants = [];
  for (const group of groups) {
    const p = await context.newPage(); p.on('pageerror', e => errors.push(e.message));
    await p.goto(origin + '/client.html?event=main'); await p.getByRole('button', { name: group, exact: true }).click(); await p.locator('#screenBtn').click(); participants.push(p);
  }
  await seek(1.25); await page.locator('#startLive').click();
  await Promise.all(participants.map((p, i) => p.waitForFunction(color => getComputedStyle(document.body).backgroundColor === color, expected[i])));
  await page.locator('#pause').click(); await seek(1.25);
  await Promise.all(participants.map((p, i) => p.waitForFunction(color => getComputedStyle(document.body).backgroundColor === color, expected[i])));
  await page.locator('#emergency').click();
  await Promise.all(participants.map(p => p.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(0, 0, 0)')));
  assert.deepEqual(errors, []);
  console.log('PASS: four participant pages receive different simultaneous colors; pause/seek and all-class stop work');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); await new Promise(r => io.close(r)); });
